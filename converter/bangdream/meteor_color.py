class UnresolvedMaterialColor(ValueError):
    """An RGB input is outside the original-native finite probe coverage."""


def unity_gamma_to_linear(value):
    """Return the probed CPU result for this exact original float32 input."""
    if isinstance(value, bool) or not isinstance(value, Real) or not math.isfinite(value):
        raise ValueError("Color RGB input must be a finite numeric value")
    try:
        bits = struct.unpack('<I', struct.pack('<f', value))[0]
    except (OverflowError, struct.error) as exc:
        raise UnresolvedMaterialColor("Color RGB input is outside float32 evidence coverage") from exc
    if bits not in _GAMMA_TO_LINEAR_BITS:
        raise UnresolvedMaterialColor(
            f"Unresolved original-native Color RGB input bits 0x{bits:08x}; no formula fallback")
    return struct.unpack('<f', struct.pack('<I', _GAMMA_TO_LINEAR_BITS[bits]))[0]

